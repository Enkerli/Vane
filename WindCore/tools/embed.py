"""Write ../WindCoreData.h from character.json, cal.txt and trims.json, so the plugin needs no files at run time."""
import json, os, numpy as np, wc, voice
T = json.load(open(voice.TRIMS)); cal = np.loadtxt(wc.CAL); C = voice.SPEC["controls"]
cur = np.loadtxt(wc.CURVES) if os.path.exists(wc.CURVES) else np.hstack([np.arange(128)[:, None], np.ones((128, 9)), np.zeros((128, 2))])
def arr(v): return "{ " + ", ".join("%.2ff" % x for x in v) + " }"
def fl(x): return repr(float(x)) + "f"
def arr5(v): return "{ " + ", ".join("%.5ff" % x for x in v) + " }"
def cstr(s): return '"' + s.encode("ascii", "replace").decode().replace("\\", "\\\\").replace('"', '\\"') + '"'
zero = [0.0] * 128
L = ["// Generated by tools/embed.py from character.json, cal.txt and trims.json. Do not edit.", "#pragma once", '#include "WindCore.h"', "",
     "namespace windcore", "{", "namespace data", "{",
     "enum Scale { kLin, kLog, kSquare };",
     "struct ControlSpec { const char* id; const char* label; const char* group; const char* lowEnd; const char* highEnd; const char* says;",
     "                     float Params::* param; float lo, hi; Scale scale; float defaultValue; int trim; };",
     "struct Trim { float cents[128]; float gain[128]; };", "",
     "inline constexpr int kNumControls = %d;" % len(C),
     "inline constexpr int kMouth = %d, kMouthDepth = %d;" % ([c["id"] for c in C].index("mouth"), [c["id"] for c in C].index("mouthDepth")),
     "inline constexpr bool kMouthIsTract = %s;   // false: the Mouth controls drive the vowel filter, which needs no tuning correction" % ("true" if voice.CONTROLS["mouth"]["param"] == "mouthFreq" else "false"),
     "inline constexpr int kNumMouthAnchors = %d;" % len(voice.MOUTH_ANCHORS),
     "inline constexpr float kMouthAnchorHz[kNumMouthAnchors] = %s;" % arr(voice.MOUTH_ANCHORS), ""]
trims = []; rows = []
for c in C:
    ti = -1
    if c.get("trim") is not False and c["id"] not in ("mouth", "mouthDepth"):
        ti = len(trims) // 2; trims += [T[c["id"] + ":0"], T[c["id"] + ":1"]]
    rows.append("    { %s, %s, %s, %s, %s, %s,\n      &Params::%s, %s, %s, %s, %s, %d }," % (cstr(c["id"]), cstr(c["label"]), cstr(c["group"]), cstr(c["ends"][0]), cstr(c["ends"][1]), cstr(c["says"]),
                c["param"], fl(c["lo"]), fl(c["hi"]), {"lin": "kLin", "log": "kLog", "square": "kSquare"}[c["scale"]], fl(c["default"]), ti))
L += ["inline const ControlSpec kControls[kNumControls] = {"] + rows + ["};", ""]
L += ["// two per trimmed control: the control at 0, then at 1", "inline const Trim kTrims[%d] = {" % len(trims)]
L += ["    { %s,\n      %s }," % (arr(t["cents"]), arr(t["gain"])) for t in trims] + ["};", ""]
L += ["// the mouth at full strength, one per anchor frequency", "inline const Trim kMouthTrims[kNumMouthAnchors] = {"]
L += ["    { %s,\n      %s }," % (arr(T["mouth@%d" % f]["cents"]), arr(T["mouth@%d" % f]["gain"])) for f in voice.MOUTH_ANCHORS] + ["};", ""]
L += ["// the default settings' own calibration", "inline const float kBaseCents[128] = %s;" % arr(cal[:, 1]), "inline const float kBaseLoud[128] = %s;" % arr(cal[:, 2]),
      "inline const float kBaseGain[128] = %s;" % arr(cal[:, 3]), "inline const float kBaseBend[128] = %s;" % arr(cal[:, 4] if cal.shape[1] > 4 else zero), "",
      "// the horn across the range (curves.txt): a multiplier per note for each setting in Curve order, then two added amounts",
      "inline const float kCurves[kNumCurves][128] = {"] + ["    %s," % arr5(cur[:, 1 + k]) for k in range(9)] + ["};",
      "inline const float kBellAdd[128] = %s;" % arr(cur[:, 10]), "inline const float kFloorAdd[128] = %s;" % arr5(cur[:, 11]), "", "} // namespace data", "} // namespace windcore", ""]
open(os.path.join(wc.ROOT, "WindCoreData.h"), "w").write("\n".join(L)); print("wrote WindCoreData.h, %d controls, %d trims" % (len(C), len(trims)))
